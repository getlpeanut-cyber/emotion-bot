// QSPI 接口发送时字节序是反的（参考库内 colorBarTest 的实现），
// 所以写颜色前要先做一次 16 位字节交换
static inline uint16_t swap16(uint16_t v)
{
    return (v >> 8) | (v << 8);
}

void screen_init()
{
    Serial.println("Initializing screen...");

    // 2. 创建 QSPI 总线
    bus = new BusQSPI(LCD_CS, LCD_SCK, LCD_D0, LCD_D1, LCD_D2, LCD_D3);
    bus->configQSPI_FreqHz(10 * 1000 * 1000); // 总线 10MHz 时钟

    // 3. 创建 ST77916 驱动器（删除手动 RST 引脚，让库去处理复位时序）
    lcd = new LCD_ST77916(bus, LCD_WIDTH, LCD_HEIGHT, 16, LCD_RST);

    // 4. 显式配置厂商初始化序列（必须在 begin() 之前调用）
    lcd->configVendorCommands(lcd_init_cmd, sizeof(lcd_init_cmd) / sizeof(lcd_init_cmd[0]));

    // 5. 初始化屏幕
    if (!lcd->begin())
    {
        Serial.println("Error: LCD begin failed!");
        return;
    }

    lcd->setDisplayOnOff(true);

    // 6. 打开背光
    pinMode(LCD_BL, OUTPUT);
    digitalWrite(LCD_BL, HIGH);

    Serial.println("Screen initialized.");
}


void screen_fill(uint16_t color)
{
    if (lcd == nullptr) {
        Serial.println("Error: Screen not initialized!");
        return;
    }

    // 准备一行缓冲区（360 像素），QSPI 需要字节交换
    static uint16_t lineBuffer[LCD_WIDTH];
    uint16_t c = swap16(color);
    for (int i = 0; i < LCD_WIDTH; i++) {
        lineBuffer[i] = c;
    }

    // 逐行绘制，timeout=-1 表示阻塞等待完成，避免缓冲区被下一行覆盖
    for (int y = 0; y < LCD_HEIGHT; y++) {
        lcd->drawBitmap(0, y, LCD_WIDTH, 1, (const uint8_t *)lineBuffer, -1);
    }

    Serial.printf("Screen filled with color: 0x%04X\n", color);
}

// 简单测试：整屏填充红色，用来确认屏幕能正常显示
void screen_test()
{
    if (lcd == nullptr) {
        Serial.println("Error: Screen not initialized!");
        return;
    }

    Serial.println("Test: fill RED...");
    screen_fill(0xF800);
}

// 可选：库自带的彩条测试（权威验证），同时验证颜色/位序是否正确
void screen_color_bar_test()
{
    if (lcd == nullptr) {
        Serial.println("Error: Screen not initialized!");
        return;
    }

    Serial.println("Color bar test...");
    lcd->colorBarTest();
    Serial.println("Color bar test done.");
}

